-- ============================================================
-- PANEL LOCALES — traduções da interface do painel de admin.
--
-- Estas chaves NÃO são as do `Strings`/`Locales` (essas traduzem
-- as mensagens do jogo). Estas traduzem o HTML estático do
-- painel: navegação, barra superior, cartões e definições.
--
-- O cliente (client/adminpanel.lua → PanelDictionary) envia a
-- tabela do idioma activo em `boot.i18n`; o NUI (html/admin/app.js
-- → applyI18n) aplica-a sobre os elementos com `data-i18n`,
-- `data-i18n-ph` e `data-i18n-title`.
--
-- É um OVERLAY: qualquer chave em falta mantém o texto inglês
-- que já está no HTML. Nunca aparece a chave crua no ecrã.
--
-- Nome do ficheiro: o fxmanifest carrega `locales/*.lua` por
-- ordem alfabética, por isso o prefixo `zz_` garante que este
-- ficheiro corre DEPOIS de pt.lua e fr.lua — que trazem as suas
-- próprias tabelas e continuam a ter prioridade.
--
-- `en` fica de fora de propósito: o HTML já está em inglês, e
-- devolver uma tabela vazia deixa o applyI18n sair logo à
-- primeira linha (zero trabalho no DOM).
-- ============================================================
