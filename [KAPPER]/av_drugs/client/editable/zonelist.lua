local allZones = {}
currentZone = "none"
if zonePolygons and next(zonePolygons) then
    for key, data in pairs(zonePolygons) do
        local temp_points = {}
        if data['points'] and next(data['points']) then
            for i=1, #data['points'] do
                temp_points[i] = {x = data['points'][i].x, y = data['points'][i].y, z = 0}
                data['points'][i] = {temp_points[i].y, temp_points[i].x}
            end
            allZones[key] = lib.zones.poly({
                points = temp_points,
                thickness = 999,
                debug = false,
                onEnter = function()
                    dbug("Entered zone:", key)
                    TriggerEvent("av_drugs:onEnter", key)
                    currentZone = key
                end,
                onExit = function()
                    dbug("Exit zone:", key)
                    TriggerEvent("av_drugs:onExit", key)
                    currentZone = "none"
                end
            })
        else
            warn("Zone with name "..key.." doesn't have any point coords, please verify it in client/editabe/zonelist")
            warn("Zone with name "..key.." doesn't have any point coords, please verify it in client/editabe/zonelist")
            warn("Zone with name "..key.." doesn't have any point coords, please verify it in client/editabe/zonelist")
        end
    end
end

function getZoneName(coords)
    local pCoords = coords or GetEntityCoords(cache.ped)
    local zoneName = "none"
    if not pCoords.x or not pCoords.y or not pCoords.z then
        warn("pCoords is missing a coord value (x,y,z)", pCoords and pCoords.x or "missing X", pCoords and pCoords.y or "missing Y", pCoords and pCoords.z or "missing Z")
        return false
    end
    if allZones and next(allZones) then
        for key, zone in pairs(allZones) do
            if zone and zone:contains(vec3(pCoords.x, pCoords.y, pCoords.z)) then
                zoneName = key
            end
        end
    end
    return zoneName
end