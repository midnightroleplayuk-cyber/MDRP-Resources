--[[
    Apex Restaurant — English locale (default / fallback)
    ────────────────────────────────────────────────────────────
    Every player-visible string in the resource lives here. To
    add another language drop a file next to this one (e.g.
    `pt.lua`, `fr.lua`) that exposes the same `Locale.<code>`
    table, then set `Config.locale` in shared/config.lua.

    Lookup happens via the global L(key, ...) helper. Missing
    keys fall back to en, then to the key itself.

    Structure mirrors the UI:
      notify.*           Player-side toasts (apex_notify)
      prompt.*           3D floating-icon zone labels
      help.*             Placement HUD / progress / menu text
      error.*            Server-callback failure reasons (NUI)
      cmd.*              Command + key-binding descriptions
      job.default.*      Defaults seeded by the createJob form
      ui.common.*        Shared widget labels (Save, Cancel…)
      ui.boss.*          Boss dashboard
      ui.editor.*        Restaurant creator
      ui.shop.*          Customer order + employee deposit UIs
      ui.register.*      POS
      ui.delivery.*      Delivery HUD
      ui.wardrobe.*      Wardrobe + uniform creator
      ui.kinds.*         Activity log "kind" labels
      ui.static.*        Hard-coded labels baked into index.html
      log.*              Activity log detail strings (DB-stored)
      loc.*              Delivery location names
]]

