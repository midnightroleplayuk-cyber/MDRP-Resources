-- ─── Lookup helper ───────────────────────────────────────────
-- Usage:
--   L('notify.duty_on')                 → 'On Duty'
--   L('notify.bought', 3, 'cola')       → 'Bought 3x cola'
-- Missing keys fall back to en, then to the key itself so the
-- UI never silently breaks if a translator forgets one.
function L(key, ...)
    local code = (Config and Config.locale) or 'en'
    local tbl  = Locale[code] or Locale.en
    local s    = tbl[key] or Locale.en[key] or key
    if select('#', ...) > 0 then
        local ok, out = pcall(string.format, s, ...)
        if ok then return out end
    end
    return s
end

-- Returns the full locale table for the active language. Used
-- by build/server/main.lua to push every string to the NUI so
-- the JS side can render localised UI without a round-trip.
function GetLocaleTable()
    local code = (Config and Config.locale) or 'en'
    return Locale[code] or Locale.en
end
