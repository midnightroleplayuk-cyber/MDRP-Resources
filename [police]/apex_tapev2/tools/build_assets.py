"""Build embedded tape images from the shipped PNGs. Run from the resource directory."""
from pathlib import Path
import base64,json,re
root=Path(__file__).resolve().parents[1]
images={p.stem:'data:image/png;base64,'+base64.b64encode(p.read_bytes()).decode('ascii') for p in sorted((root/'textures').glob('*.png'))}
# Original style IDs predate the *_tape filenames.
for style in ('police','fire','ambulance','crime'):
    images[style]=images.pop(style+'_tape')
(root/'html/menu/assets.js').write_text('/* Generated by tools/build_assets.py */\nglobalThis.ApexTapeImages='+json.dumps(images,separators=(',',':'))+';\n',encoding='utf8')
(root/'client/textures.lua').write_text('-- Generated by tools/build_assets.py; local images only.\nTapeImageData={\n'+''.join('['+json.dumps(k)+']='+json.dumps(v)+',\n' for k,v in images.items())+'}\n',encoding='utf8')
print(f'Built {len(images)} embedded images for NUI and native runtime textures')
