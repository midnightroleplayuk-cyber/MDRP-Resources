CREATE TABLE IF NOT EXISTS `hf1_display_vehicles` (
  `id` INT UNSIGNED NOT NULL AUTO_INCREMENT,
  `name` VARCHAR(60) NOT NULL,
  `model` VARCHAR(60) NOT NULL,
  `plate` VARCHAR(8) NOT NULL DEFAULT 'DISPLAY',
  `x` DOUBLE NOT NULL,
  `y` DOUBLE NOT NULL,
  `z` DOUBLE NOT NULL,
  `heading` DOUBLE NOT NULL DEFAULT 0,
  `rotating` TINYINT(1) NOT NULL DEFAULT 0,
  `speed` DOUBLE NOT NULL DEFAULT 8,
  `primary_color` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  `secondary_color` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  PRIMARY KEY (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
