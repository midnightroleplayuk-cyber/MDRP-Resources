function Locales.t(key, ...)
    local lang = (Config and Config.locale) or 'en'
    local s = (Locales[lang] and Locales[lang][key]) or Locales.en[key] or key
    local n = select('#', ...)
    if n == 0 then return s end
    -- Sequentially replace each %s with the next arg.
    local args, i = { ... }, 0
    return (s:gsub('%%s', function()
        i = i + 1
        return tostring(args[i])
    end))
end


-- Returns a FLAT table for the ACTIVE language: the English base with
-- the configured language (Config.locale) overlaid on top, so any key
-- that lacks a translation still resolves to English instead of showing
-- a raw key. Carries __lang so the NUI can set <html lang>. This is the
-- table the client pushes to the NUI on bootstrap — switching
-- Config.locale here is what actually changes the UI language.
function Locales.active(lang)
    lang = lang or (Config and Config.locale) or 'en'
    local out = {}
    for k, v in pairs(Locales.en or {}) do out[k] = v end
    if lang ~= 'en' and Locales[lang] then
        for k, v in pairs(Locales[lang]) do out[k] = v end
    end
    out.__lang = lang
    return out
end

